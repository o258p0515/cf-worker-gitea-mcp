import type { ToolDef } from "./types";
import { systemUserTools } from "./tools/system-user";
import { repositoryFileTools } from "./tools/repository-file";
import { gitRefTools } from "./tools/git-refs";
import { issuePrTools } from "./tools/issues-prs";
import { actionsTools } from "./tools/actions";
import { managementTools } from "./tools/management";
export const tools:ToolDef[]=[...systemUserTools,...repositoryFileTools,...gitRefTools,...issuePrTools,...actionsTools,...managementTools];
export const TOOL_NAMES=tools.map(t=>t.name);
if(tools.length!==48||new Set(TOOL_NAMES).size!==48)throw new Error(`Expected 48 unique MCP tools, got ${tools.length} total / ${new Set(TOOL_NAMES).size} unique`);
